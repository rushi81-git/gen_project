import asyncio
import time
from typing import Dict, Any

class MockProvider:
    """
    Mock inference provider for local development, UI testing, and CI automated tests.
    Responses are explicitly marked as simulated.
    """

    @staticmethod
    async def generate(
        model_id: str,
        prompt: str,
        max_tokens: int = 128,
        temperature: float = 0.7,
        simulate_delay_ms: int = 0,
        simulate_error: bool = False
    ) -> Dict[str, Any]:
        if simulate_delay_ms > 0:
            await asyncio.sleep(simulate_delay_ms / 1000.0)

        if simulate_error:
            raise RuntimeError(f"Simulated execution error triggered on model '{model_id}'")

        # ponytail: standard library approximation, ~4 chars per token
        prompt_tokens = max(1, len(prompt) // 4)
        
        # Formulate contextual simulated response
        clean_prompt = prompt.strip().replace("\n", " ")
        if len(clean_prompt) > 60:
            clean_prompt = clean_prompt[:60] + "..."

        simulated_text = (
            f"[MOCK / SIMULATION] Based on your query regarding '{clean_prompt}', "
            f"this is a simulated response generated by '{model_id}'. "
            f"The model operated with temperature={temperature} and max_tokens={max_tokens}. "
            f"No live cloud inference charges or GPU memory were consumed."
        )

        completion_tokens = max(1, len(simulated_text) // 4)
        total_tokens = prompt_tokens + completion_tokens

        # Estimated cost for mock is 0.00
        return {
            "text": simulated_text,
            "prompt_tokens": prompt_tokens,
            "completion_tokens": completion_tokens,
            "total_tokens": total_tokens,
            "tokens_estimated": True,
            "cost_usd": 0.0,
            "is_mock": True
        }
